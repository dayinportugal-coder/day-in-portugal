# -*- coding: utf-8 -*-
"""Builds experiences.js, /experiences/*.html, the sitemap entries, DIP_PAGES and the
'Book it' boxes in the guides from tools/experiences_data.py. Idempotent.
Run from the repo root: python3 tools/experiences_build.py"""
import json, os, re, sys, html
sys.path.insert(0, os.path.dirname(__file__))
import experiences_data as D
ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
SITE = "https://dayinportugal.com"
LANGS = ["en", "pt", "es", "fr", "de"]
E = html.escape
BY = {i["id"]: i for i in D.ITEMS}

def track(href, tag):
    if not href: return href
    if "tp.media/r" in href:
        return re.sub(r"sub_id=[^&]*", "sub_id=" + tag, href)
    if "getyourguide.com" in href:
        href = re.sub(r"&cmp=[^&]*", "", href)
        return href + "&cmp=" + tag
    return href

def euro(p):
    return "€%d" % p if float(p).is_integer() else "€%.2f" % p

def read(p): return open(os.path.join(ROOT, p), encoding="utf-8").read()
def write(p, s):
    full = os.path.join(ROOT, p); os.makedirs(os.path.dirname(full), exist_ok=True)
    open(full, "w", encoding="utf-8").write(s)

# ---------------------------------------------------------------- experiences.js
def build_js():
    items = []
    for i in D.ITEMS:
        o = {k: i[k] for k in ("id", "slug", "place", "group", "img", "guide", "name", "meta") if k in i}
        for k in ("href", "partner", "price", "unit", "rating", "reviews", "fc", "badge", "new"):
            if i.get(k) is not None and i.get(k) is not False: o[k] = i[k]
        if i.get("price") is not None: o["checked"] = D.CHECKED
        items.append(o)
    old = json.load(open("/tmp/exp_old.json")) if os.path.exists("/tmp/exp_old.json") else None
    ui = json.loads(json.dumps(old["ui"])) if old else {}
    for l in LANGS:
        ui.setdefault(l, {}).update(D.UI_NEW[l]); ui[l]["priceNote"] = D.PRICE_NOTE[l]
    js = ("/* Day in Portugal — experiences (home cards, map, /experiences/ pages).\n"
          "   GENERATED by tools/experiences_build.py from tools/experiences_data.py — edit there.\n"
          "   Prices, ratings and free-cancellation flags were read on each partner page on " + D.CHECKED + ".\n"
          "   track(href, tag) adds our click tag: cmp= for GetYourGuide, sub_id= for Travelpayouts links. */\n"
          "window.DIP_EXP = (function () {\n  var places = " + json.dumps(D.PLACES, ensure_ascii=False) +
          ";\n  var items = " + json.dumps(items, ensure_ascii=False, indent=1) +
          ";\n  var ui = " + json.dumps(ui, ensure_ascii=False, indent=1) + ";\n"
          "  function track(href, tag) {\n    if (!href) return href;\n"
          "    if (href.indexOf(\"tp.media/r\") >= 0) return href.replace(/sub_id=[^&]*/, \"sub_id=\" + tag);\n"
          "    if (href.indexOf(\"getyourguide.com\") >= 0) return href.replace(/&cmp=[^&]*/, \"\") + \"&cmp=\" + tag;\n"
          "    return href;\n  }\n"
          "  return { places: places, items: items, ui: ui, track: track, checked: \"" + D.CHECKED + "\" };\n})();\n")
    write("experiences.js", js)

# ---------------------------------------------------------------- pages
TPL = read("porto-river-cruise.html")
HEADER = TPL[TPL.index("<body>"):TPL.index("<main")]
FOOTER = TPL[TPL.index("</main>") + len("</main>"):]
HEAD_TAIL = TPL[TPL.index('  <link rel="icon"'):TPL.index('  <script type="application/ld+json">')]
HEAD_SCRIPTS = TPL[TPL.index('  <script src="/lang.js"'):TPL.index("</head>")]

def credit(img):
    f, a, lic, lurl, big = D.PHOTOS[img]
    page = "https://commons.wikimedia.org/wiki/File:" + f.replace(" ", "_")
    return ('Photo: <a href="%s" rel="noopener" target="_blank">%s</a> · <a href="%s" rel="license noopener" target="_blank">%s</a>, via Wikimedia Commons'
            % (E(page), E(a), lurl, lic))

def head(title, desc, url, img, ld):
    return ('<!DOCTYPE html>\n<html lang="en">\n<head>\n  <meta charset="UTF-8" />\n  <meta name="viewport" content="width=device-width, initial-scale=1" />\n'
            '  <title>%s | Day in Portugal</title>\n  <meta name="description" content="%s" />\n'
            '  <link rel="canonical" href="%s" />\n  <link rel="alternate" hreflang="en" href="%s" />\n  <link rel="alternate" hreflang="x-default" href="%s" />\n'
            '  <meta name="robots" content="index,follow" />\n  <meta name="theme-color" content="#faf6ef" />\n'
            '  <meta property="og:type" content="website" />\n  <meta property="og:site_name" content="Day in Portugal" />\n  <meta property="og:locale" content="en_GB" />\n'
            '  <meta property="og:url" content="%s" />\n  <meta property="og:title" content="%s" />\n  <meta property="og:description" content="%s" />\n'
            '  <meta property="og:image" content="%s" />\n  <meta name="twitter:card" content="summary_large_image" />\n'
            % (E(title), E(desc), url, url, url, url, E(title), E(desc), SITE + img)
            + HEAD_TAIL + '  <link rel="stylesheet" href="/experience.css" />\n'
            + '  <script type="application/ld+json">' + json.dumps(ld, ensure_ascii=False) + '</script>\n' + HEAD_SCRIPTS + "</head>\n")

def facts_html(i):
    rows = []
    if i.get("dur"): rows.append(("Duration", i["dur"]))
    if i.get("meet"): rows.append(("Where", i["meet"]))
    if i.get("partner"): rows.append(("Booked on", i["partner"]))
    return '<dl class="xpp-facts">' + "".join("<div><dt>%s</dt><dd>%s</dd></div>" % (E(a), E(b)) for a, b in rows) + "</dl>"

def mini(j, tag):
    p = D.PLACES[j["place"]]["name"]["en"]
    price = ('<span class="xpp-mini-price">from %s</span>' % euro(j["price"])) if j.get("price") else '<span class="xpp-mini-price">Free guide</span>'
    return ('<a class="xpp-mini" href="/experiences/%s"><img src="%s" width="640" height="427" alt="" loading="lazy" decoding="async" />'
            '<span class="xpp-mini-body"><span class="xpp-mini-place">%s</span><strong>%s</strong>%s</span></a>' % (j["slug"], j["img"], E(p), E(j["name"]["en"]), price))

def price_box(i, tag):
    if not i.get("href"):
        return ('<aside class="xpp-box"><p class="xpp-free">Free guide</p><p class="muted">No ticket needed. Our guide has the trains, times and what to see.</p>'
                '<a class="btn xpp-book" href="%s">Read the free guide</a></aside>' % i["guide"])
    unit = "per group up to 4" if i.get("unit") == "group" else "per person"
    rows = ['<p class="xpp-price"><span>from</span> %s <small>%s</small></p>' % (euro(i["price"]), unit),
            '<p class="xpp-src">Price on %s, checked 15 Nov 2026.</p>' % E(i["partner"])]
    if i.get("rating"):
        rows.append('<p class="xpp-rating"><span aria-hidden="true">★</span> %.1f / 5 · %s reviews on %s <span class="xpp-src">(15 Nov 2026)</span></p>' % (i["rating"], format(i["reviews"], ","), E(i["partner"])))
    if i.get("fc"):
        rows.append('<p class="xpp-fc">✓ Free cancellation up to 24 hours before, as stated on the %s page on 15 Nov 2026.</p>' % E(i["partner"]))
    rows.append('<a class="btn xpp-book" href="%s" rel="sponsored nofollow noopener" target="_blank">See dates &amp; book on %s<span class="sr-only"> (opens partner site)</span></a>' % (E(track(i["href"], tag)), E(i["partner"])))
    rows.append('<p class="xpp-aff">Affiliate link: you pay the partner’s public price and we may earn a commission. <a href="/disclosure">How we earn</a>.</p>')
    return '<aside class="xpp-box">' + "".join(rows) + "</aside>"

def page(i):
    url = SITE + "/experiences/" + i["slug"]
    big = D.PHOTOS[i["img"]][4]
    place = D.PLACES[i["place"]]["name"]["en"]
    trip = {"@context": "https://schema.org", "@type": "TouristTrip", "name": i["name"]["en"], "description": i["desc"], "url": url,
            "image": [SITE + big], "inLanguage": "en", "touristType": "Leisure"}
    if i.get("href"):
        trip["offers"] = {"@type": "Offer", "price": "%.2f" % i["price"], "priceCurrency": "EUR", "url": track(i["href"], "exp_" + i["id"]),
                          "validFrom": D.CHECKED, "availability": "https://schema.org/InStock", "offeredBy": {"@type": "Organization", "name": i["partner"]}}
        if i.get("unit") == "group":
            trip["offers"]["eligibleQuantity"] = {"@type": "QuantitativeValue", "maxValue": 4, "unitText": "people per group"}
    crumbs = {"@context": "https://schema.org", "@type": "BreadcrumbList", "itemListElement": [
        {"@type": "ListItem", "position": 1, "name": "Home", "item": SITE + "/"},
        {"@type": "ListItem", "position": 2, "name": "Experiences", "item": SITE + "/experiences/"},
        {"@type": "ListItem", "position": 3, "name": i["name"]["en"], "item": url}]}
    near = [j for j in D.ITEMS if j["id"] != i["id"] and (j["place"] == i["place"] or j["group"] == i["group"])][:3]
    inc = ""
    if i.get("inc"):
        inc += '<div class="xpp-list"><h2>What’s included</h2><ul class="xpp-inc">' + "".join("<li>%s</li>" % E(x) for x in i["inc"]) + "</ul>"
        if i.get("exc"): inc += '<h3>Not included</h3><ul class="xpp-exc">' + "".join("<li>%s</li>" % E(x) for x in i["exc"]) + "</ul>"
        inc += '<p class="xpp-src">As listed on the %s product page (“%s”) on 15 Nov 2026.</p></div>' % (E(i["partner"]), E(i["pname"]))
    body = (HEADER + '  <main id="main" class="wrap xpp">\n'
        '  <nav class="xpp-crumbs" aria-label="Breadcrumb"><a href="/">Home</a> › <a href="/experiences/">Experiences</a> › <span>%s</span></nav>\n'
        '  <div class="xpp-top">\n  <figure class="xpp-hero"><img src="%s" srcset="%s 640w, %s 1200w" sizes="(min-width: 960px) 60vw, 100vw" width="1200" height="800" alt="%s" fetchpriority="high" decoding="async" />'
        '<figcaption>%s</figcaption></figure>\n'
        '  <div class="xpp-intro"><p class="kicker">%s%s</p><h1>%s</h1><p class="xpp-lead">%s</p>%s%s</div>\n  </div>\n'
        % (E(i["name"]["en"]), big, i["img"], big, E(i["name"]["en"] + " — " + place), credit(i["img"]),
           E(place), (" · " + E(i["partner"])) if i.get("partner") else "", E(i["name"]["en"]), E(i["lead"]), facts_html(i), price_box(i, "exp_" + i["id"])))
    body += '  <div class="xpp-cols">' + inc + '<div class="xpp-list"><h2>Good to know</h2><ul class="xpp-tips">' + "".join("<li>%s</li>" % E(x) for x in i["tips"]) + "</ul>"
    body += ('<p class="xpp-links"><a class="xpp-guide" href="%s">Read our full guide</a> · <a href="/#map">See it on the map of Portugal</a> · <a href="/experiences/">All experiences</a></p></div></div>\n' % i["guide"])
    body += '  <section class="xpp-near" aria-labelledby="near-h"><h2 id="near-h">More to book nearby</h2><div class="xpp-near-grid">' + "".join(mini(j, "") for j in near) + "</div></section>\n"
    body += "  </main>" + FOOTER
    return head(i["title"], i["desc"], url, big, [trip, crumbs]) + body

def hub():
    url = SITE + "/experiences/"
    groups = [("porto", "In Porto"), ("trips", "Day trips"), ("lisbon", "Lisbon and around")]
    ld = [{"@context": "https://schema.org", "@type": "ItemList", "name": "Experiences in Portugal", "itemListElement": [
        {"@type": "ListItem", "position": n + 1, "url": SITE + "/experiences/" + i["slug"], "name": i["name"]["en"]} for n, i in enumerate(D.ITEMS)]}]
    body = (HEADER + '  <main id="main" class="wrap xpp xpp-hubpage">\n  <nav class="xpp-crumbs" aria-label="Breadcrumb"><a href="/">Home</a> › <span>Experiences</span></nav>\n'
            '  <header class="xpp-hubhead"><p class="kicker">Experiences</p><h1>Things to book in Portugal, <em>with real prices.</em></h1>'
            '<p class="xpp-lead">Tours, tickets and classes we link to from our guides, with the from-price, rating and cancellation terms shown on the partner’s page on 15 Nov 2026. '
            'Prefer a map? <a href="/#map">See them on the map of Portugal</a>.</p></header>\n')
    for g, label in groups:
        body += '  <section class="xpp-hubsec"><h2>%s</h2><div class="xpp-near-grid">%s</div></section>\n' % (label, "".join(mini(i, "") for i in D.ITEMS if i["group"] == g))
    body += '  <p class="xpp-src">%s</p>\n  </main>' % E(D.PRICE_NOTE["en"]) + FOOTER
    return head("Things to book in Portugal: tours, tickets and day trips", "Porto, Douro, Lisbon and Sintra experiences with real from-prices, ratings and free-cancellation terms checked on GetYourGuide, Tiqets and WeGoTrip on 15 Nov 2026.", url, "/img/exp/tagus-sailboats-1200.webp", ld) + body

def build_pages():
    for i in D.ITEMS: write("experiences/%s.html" % i["slug"], page(i))
    write("experiences/index.html", hub())

# ---------------------------------------------------------------- sitemap + DIP_PAGES
def build_sitemap():
    s = read("sitemap.xml")
    s = re.sub(r"  <url><loc>https://dayinportugal.com/experiences/[^<]*</loc>.*?</url>\n", "", s)
    add = "".join("  <url><loc>%s</loc><lastmod>%s</lastmod></url>\n" % (u, D.CHECKED)
                  for u in [SITE + "/experiences/"] + [SITE + "/experiences/" + i["slug"] for i in D.ITEMS])
    s = s.replace("</urlset>", add + "</urlset>")
    write("sitemap.xml", s)
    pl = read("page-langs.js")
    m = re.search(r'window\.DIP_PAGES=(\{.*\});?', pl, re.S)
    data = json.loads(m.group(1))
    en = [p for p in data["en"] if not p.startswith("/experiences")]
    en += ["/experiences"] + ["/experiences/" + i["slug"] for i in D.ITEMS]
    data["en"] = en
    write("page-langs.js", pl[:m.start(1)] + json.dumps(data, ensure_ascii=False, separators=(",", ":")) + pl[m.end(1):])

